"""
The college block collision, for any level that instances the /Game/Campus/Meshes/SM_Campus_* art.

Importing this module has no side effects: call build().

WHY IT EXISTS
  The campus art meshes are built with enable_collision=False (Scripts/build_campus.py), so they are
  pure draw calls with no physics at all. In L_Match the collision is a separate, invisible box set
  generated by Scripts/build_collision.py from the games own export (export/unreal/college_boxes.json):
  9720 solid boxes, 30245 thin pieces and 45 stair ramps, which is every floor plate, every interior
  and exterior wall, every doorway reveal, every pole, rail and grill rod of the college, 1:1 with the
  art. L_VarsityValley instances the same art at a different origin, so it needs the same box set at
  that origin. It used to get one axis-aligned bounding box per building part instead, which is a solid
  invisible brick: no floors above ground level, no rooms, no stairs, and every doorway sealed.

WHY BOXES AND NOT COMPLEX-AS-SIMPLE
  CTF_USE_COMPLEX_AS_SIMPLE on the merged campus art would mean cooking a triangle collision mesh for
  every SM_Campus_* part and running every capsule sweep and every bullet against a triangle BVH of a
  few hundred thousand triangles, on a phone, for a 50 player match. The box set is the same geometry
  expressed as the cheapest primitive Chaos has, it is already tuned (doorways open, stair ramps
  walkable, railings shootable), and it is already shipping in L_Match on device. Complex collision is
  kept only for the handful of genuinely non-box pieces (gazebo roof, zipline towers), which arrive as
  college_boxes_extra.glb and do use CTF_USE_COMPLEX_AS_SIMPLE.

THE THREE OBJECT TYPES, AND WHY
  solid  WorldStatic, BlockAll          floors, walls, stairs steps, slabs: blocks players and bullets
  thin   PhysicsBody, blocks all but    grill rods, railings, posts: a player cannot walk through them,
         ignores Camera                 but the gun traces WorldStatic / WorldDynamic / Pawn objects,
                                        so bullets pass between the rods like in the three.js game
  ramps  WorldStatic, blocks all but    the invisible slope over each flight of steps, so the capsule
         ignores Visibility and Camera  walks up smoothly. Campus/CampusShotTrace.h skips any component
                                        that ignores ECC_Visibility, which is exactly this signature,
                                        so bullets and bot sight see the real steps, not the slope.
"""
import json
import os

import unreal

DATA = os.environ.get("CAMPUS_DATA", r"C:\Users\durga\Desktop\tree js game\college-game\export\unreal")
BOXES = "college_boxes.json"
EXTRA = "college_boxes_extra.glb"
CHUNK = 1500          # KBoxElems per mesh, as in build_collision.py
THIN_CM = 15.0 * 1.1  # the export THIN_FOR_CAMERA; the boxes are vertically scaled 1.1 in the game

EAL = unreal.EditorAssetLibrary
AT = unreal.AssetToolsHelpers.get_asset_tools()
ML = unreal.MathLibrary


def _box_mesh(path, rows, shift):
    """One invisible box-aggregate mesh: a run of export rows as KBoxElems, shifted to the anchor."""
    if EAL.does_asset_exist(path):
        EAL.delete_asset(path)
    mesh = EAL.duplicate_asset("/Engine/BasicShapes/Cube", path)
    if mesh is None:
        raise RuntimeError("could not create %s (an actor may still reference the old asset)" % path)
    body = mesh.get_editor_property("body_setup")
    agg = body.get_editor_property("agg_geom")
    elements = []
    for row in rows:
        element = unreal.KBoxElem()
        element.set_editor_property("center", unreal.Vector(*row["c"]) + shift)
        # the export gives each box its own X and Y axes in Unreal space, with s in that axis order
        element.set_editor_property("rotation", ML.make_rot_from_xy(unreal.Vector(*row["x"]),
                                                                   unreal.Vector(*row["y"])))
        # FKBoxElem X/Y/Z are the FULL dimensions of the box; the engine halves them itself
        element.set_editor_property("x", max(row["s"][0], 1.0))
        element.set_editor_property("y", max(row["s"][1], 1.0))
        element.set_editor_property("z", max(row["s"][2], 1.0))
        elements.append(element)
    agg.set_editor_property("box_elems", elements)
    agg.set_editor_property("sphere_elems", [])
    agg.set_editor_property("sphyl_elems", [])
    agg.set_editor_property("convex_elems", [])
    body.set_editor_property("agg_geom", agg)
    body.set_editor_property("collision_trace_flag", unreal.CollisionTraceFlag.CTF_USE_SIMPLE_AS_COMPLEX)
    EAL.save_loaded_asset(mesh)
    return mesh


def _place(eas, mesh, label, folder):
    """An invisible collider actor at the world origin: the KBoxElems already carry world positions."""
    actor = eas.spawn_actor_from_class(unreal.StaticMeshActor, unreal.Vector(0.0, 0.0, 0.0),
                                       unreal.Rotator(0.0, 0.0, 0.0))
    actor.static_mesh_component.set_static_mesh(mesh)
    actor.set_actor_label(label)
    actor.set_folder_path(folder)
    component = actor.static_mesh_component
    component.set_mobility(unreal.ComponentMobility.STATIC)
    component.set_collision_profile_name("BlockAll")
    component.set_editor_property("visible", False)
    component.set_editor_property("hidden_in_game", True)
    component.set_editor_property("cast_shadow", False)
    return actor


def _extra_mesh(asset_dir, log):
    """The non-box pieces (gazebo, zipline towers) as exact triangles."""
    source = os.path.join(DATA, EXTRA)
    if not os.path.isfile(source):
        log("WARN %s is missing: no triangle collision for the gazebo / ziplines" % source)
        return None
    task = unreal.AssetImportTask()
    task.filename = source
    task.destination_path = asset_dir + "/Extra"
    task.automated = True
    task.replace_existing = True
    task.save = True
    AT.import_asset_tasks([task])
    meshes = [a for a in (unreal.load_asset(p) for p in task.imported_object_paths)
              if isinstance(a, unreal.StaticMesh)]
    if not meshes:
        log("WARN %s imported no static mesh" % EXTRA)
        return None
    mesh = meshes[0]
    unreal.EditorStaticMeshLibrary.remove_collisions(mesh)
    mesh.get_editor_property("body_setup").set_editor_property(
        "collision_trace_flag", unreal.CollisionTraceFlag.CTF_USE_COMPLEX_AS_SIMPLE)
    EAL.save_loaded_asset(mesh)
    return mesh


def clear(eas, prefix):
    """Destroy every collider actor this module placed before (so a re-run does not stack them)."""
    removed = 0
    for actor in eas.get_all_level_actors():
        if actor.get_actor_label().startswith(prefix):
            eas.destroy_actor(actor)
            removed += 1
    return removed


def build(eas, anchor, asset_dir, folder, prefix, log=None):
    """Place the whole college collision for an art copy rooted at anchor.

    eas        EditorActorSubsystem for the already-loaded level
    anchor     where the SM_Campus_* art actors sit, as (x, y, z)
    asset_dir  content folder for the generated collision meshes, e.g. /Game/VarsityValley/Collision
    folder     the level outliner folder for the actors
    prefix     actor label prefix, e.g. VVColCollege_
    """
    log = log or (lambda message: unreal.log("[college collision] %s" % message))
    shift = unreal.Vector(float(anchor[0]), float(anchor[1]), float(anchor[2]))
    with open(os.path.join(DATA, BOXES)) as handle:
        rows = json.load(handle)

    is_thin = lambda row: sorted(row["s"])[1] < THIN_CM
    ramps = [r for r in rows if r.get("r")]
    thin = [r for r in rows if not r.get("r") and is_thin(r)]
    solid = [r for r in rows if not r.get("r") and not is_thin(r)]
    # sort by position so each chunk is a compact area, which keeps the broadphase bounds tight
    solid.sort(key=lambda r: (int(r["c"][0] // 3000), int(r["c"][1] // 3000), r["c"][2]))
    thin.sort(key=lambda r: (int(r["c"][0] // 3000), int(r["c"][1] // 3000), r["c"][2]))

    removed = clear(eas, prefix)
    log("college collision at anchor %s: removed %d old actors" % (tuple(anchor), removed))

    counts = {"solid": len(solid), "thin": len(thin), "ramps": len(ramps), "actors": 0}

    for index in range(0, len(solid), CHUNK):
        mesh = _box_mesh("%s/SM_%sSolid_%02d" % (asset_dir, prefix.rstrip("_"), index // CHUNK),
                         solid[index:index + CHUNK], shift)
        _place(eas, mesh, "%sSolid_%02d" % (prefix, index // CHUNK), folder)
        counts["actors"] += 1
        unreal.SystemLibrary.collect_garbage()

    for index in range(0, len(thin), CHUNK):
        mesh = _box_mesh("%s/SM_%sThin_%02d" % (asset_dir, prefix.rstrip("_"), index // CHUNK),
                         thin[index:index + CHUNK], shift)
        actor = _place(eas, mesh, "%sThin_%02d" % (prefix, index // CHUNK), folder)
        component = actor.static_mesh_component
        # PhysicsBody: the player capsule (Pawn blocks PhysicsBody) and Visibility traces (vault,
        # foot IK) still hit it, but the gun only queries WorldStatic / WorldDynamic / Pawn OBJECTS,
        # so bullets pass between the rods of a railing exactly as in the three.js game.
        component.set_collision_profile_name("Custom")
        component.set_collision_enabled(unreal.CollisionEnabled.QUERY_AND_PHYSICS)
        component.set_collision_object_type(unreal.CollisionChannel.ECC_PHYSICS_BODY)
        component.set_collision_response_to_all_channels(unreal.CollisionResponseType.ECR_BLOCK)
        component.set_collision_response_to_channel(unreal.CollisionChannel.ECC_CAMERA,
                                                    unreal.CollisionResponseType.ECR_IGNORE)
        counts["actors"] += 1
        unreal.SystemLibrary.collect_garbage()

    if ramps:
        mesh = _box_mesh("%s/SM_%sRamps" % (asset_dir, prefix.rstrip("_")), ramps, shift)
        actor = _place(eas, mesh, "%sRamps" % prefix, folder)
        component = actor.static_mesh_component
        # WorldStatic so the capsule walks up the slope, but IGNORING Visibility and Camera so the
        # foot IK, vaulting and Campus/CampusShotTrace.h see the real steps underneath it.
        component.set_collision_profile_name("Custom")
        component.set_collision_enabled(unreal.CollisionEnabled.QUERY_AND_PHYSICS)
        component.set_collision_object_type(unreal.CollisionChannel.ECC_WORLD_STATIC)
        component.set_collision_response_to_all_channels(unreal.CollisionResponseType.ECR_BLOCK)
        component.set_collision_response_to_channel(unreal.CollisionChannel.ECC_VISIBILITY,
                                                    unreal.CollisionResponseType.ECR_IGNORE)
        component.set_collision_response_to_channel(unreal.CollisionChannel.ECC_CAMERA,
                                                    unreal.CollisionResponseType.ECR_IGNORE)
        counts["actors"] += 1
        log("stair ramps: pawn %s visibility %s camera %s" % (
            component.get_collision_response_to_channel(unreal.CollisionChannel.ECC_PAWN),
            component.get_collision_response_to_channel(unreal.CollisionChannel.ECC_VISIBILITY),
            component.get_collision_response_to_channel(unreal.CollisionChannel.ECC_CAMERA)))

    extra = _extra_mesh(asset_dir, log)
    if extra:
        actor = eas.spawn_actor_from_class(unreal.StaticMeshActor, shift, unreal.Rotator(0.0, 0.0, 0.0))
        actor.static_mesh_component.set_static_mesh(extra)
        actor.set_actor_label("%sExtra" % prefix)
        actor.set_folder_path(folder)
        component = actor.static_mesh_component
        component.set_mobility(unreal.ComponentMobility.STATIC)
        component.set_collision_profile_name("BlockAll")
        component.set_editor_property("visible", False)
        component.set_editor_property("hidden_in_game", True)
        component.set_editor_property("cast_shadow", False)
        counts["actors"] += 1
        counts["extra"] = 1

    log("college collision: %d solid + %d thin boxes + %d ramps on %d actors"
        % (counts["solid"], counts["thin"], counts["ramps"], counts["actors"]))
    return counts
